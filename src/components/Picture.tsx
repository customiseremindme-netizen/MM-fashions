import type { CSSProperties } from "react";
import { photoInfo } from "@/lib/photos";
import { cn } from "@/lib/utils";

type PictureProps = {
  /** Supplied photo path, e.g. "/photos/kg2.jpg". */
  src: string;
  alt: string;
  /** `sizes` attribute for the WebP srcset. */
  sizes: string;
  className?: string;
  style?: CSSProperties;
  /** The page's main above-the-fold image: load eagerly with high priority. */
  priority?: boolean;
  /** Above the fold but not the main image: load eagerly. */
  eager?: boolean;
  /** Override the fetch priority, e.g. "low" for decorative images. */
  fetchPriority?: "high" | "low" | "auto";
};

/**
 * A supplied photo served as responsive WebP (generated by `npm run images`),
 * falling back to the original file. Width and height are always set so the
 * browser reserves space before the image loads.
 */
export function Picture({ src, alt, sizes, className, style, priority, eager, fetchPriority }: PictureProps) {
  const info = photoInfo(src);
  return (
    <picture className="contents">
      {info.srcSet && <source type="image/webp" srcSet={info.srcSet} sizes={sizes} />}
      <img
        src={src}
        alt={alt}
        width={info.width}
        height={info.height}
        loading={priority || eager ? "eager" : "lazy"}
        decoding={priority ? "auto" : "async"}
        fetchPriority={fetchPriority ?? (priority ? "high" : undefined)}
        className={cn("block", className)}
        style={style}
      />
    </picture>
  );
}
